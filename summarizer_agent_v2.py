# USER INSTRUCTION PARSER
# ══════════════════════════════════════════════════════════════════════════

def parse_user_command(instructions: str) -> Tuple[str, List[str]]:
    if not instructions: return "detailed_digest", []
    inst_lower = instructions.lower().strip()
    output_format = "detailed_digest"
    modules = []
    for shortcut, action in USER_SHORTCUTS.items():
        if shortcut in inst_lower:
            if action.startswith("_module_"):
                modules.append(action[len("_module_"):])
            else:
                output_format = action
                if action == "chronology": modules.append("chronology")
                elif action == "issue_wise": modules.append("issue_wise")
                elif action == "clause_table": modules.append("clause_table")
                elif action == "risk_report": modules.append("risk")
    if "contradiction" in inst_lower or "conflict" in inst_lower:
        modules.append("contradictions")
    if "missing" in inst_lower and "provision" in inst_lower:
        modules.append("missing_provisions")
    if "procedural" in inst_lower:
        modules.append("procedural")
    return output_format, list(dict.fromkeys(modules))


