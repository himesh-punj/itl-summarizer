def anchor_document(text: str) -> Tuple[str, Dict[int, str]]:
    """Insert [\u00b6N] anchors into the text for precise citation. Returns
    (anchored_text, anchor_map) where anchor_map[N] is the first 200 chars
    of paragraph N (for verifier matching)."""
    if not text: return text, {}
    raw_paras = re.split(r'\n\s*\n', text)
    anchored = []
    anchor_map = {}
    pn = 0
    for p in raw_paras:
        p = p.strip()
        if not p: continue
        pn += 1
        anchored.append(f"[\u00b6{pn}] {p}")
        anchor_map[pn] = p[:200]
    return "\n\n".join(anchored), anchor_map


def detect_paragraph_refs(output: str) -> List[int]:
    refs = set()
    for m in re.finditer(r'\[?\u00b6\s*(\d{1,4})\]?', output):
        refs.add(int(m.group(1)))
    for m in re.finditer(r'\b[Pp]ara(?:graph)?\s*(\d{1,4})\b', output):
        refs.add(int(m.group(1)))
    return sorted(refs)


