# AGENT 6 — SOURCE-GROUNDING VERIFIER (Steps 5+6)
# ══════════════════════════════════════════════════════════════════════════

def verify_source_grounding(output: str, doc_text: str,
                            anchor_map: Dict[int, str]) -> Dict[str, Any]:
    issues = []

    # 1. Paragraph references must exist
    refs = detect_paragraph_refs(output)
    invalid = [r for r in refs if r not in anchor_map]
    if invalid:
        issues.append({"type": "INVALID_PARA_REFS", "severity": "HIGH",
                       "note": f"Output references paragraphs not in document: {invalid[:10]}",
                       "refs": invalid})

    # 2. Banned phrases
    banned = []
    for pat in BANNED_PHRASES:
        for m in re.finditer(pat, output, re.IGNORECASE):
            ctx = output[max(0, m.start()-30):m.end()+30]
            banned.append({"phrase": m.group(0), "context": ctx})
    if banned:
        issues.append({"type": "BANNED_PHRASES", "severity": "MEDIUM",
                       "note": f"{len(banned)} banned hedge phrase(s)",
                       "occurrences": banned[:5]})

    # 3. Settled-law strict ban
    if re.search(r'\bsettled law\b|\bwell[-\s]?settled\b', output, re.IGNORECASE):
        issues.append({"type": "SETTLED_LAW_CLAIM", "severity": "HIGH",
                       "note": "Output claims 'settled law' \u2014 forbidden under Step 6 unless quoted from document."})

    # 4. Inference language
    inference_pats = [
        r"\bthis means that\b", r"\btherefore (?:the court|the authority) would\b",
        r"\bwould likely\b", r"\bmay be expected to\b",
    ]
    inferences = [p for p in inference_pats if re.search(p, output, re.IGNORECASE)]
    if inferences:
        issues.append({"type": "INFERENCE_LANGUAGE", "severity": "MEDIUM",
                       "note": f"Inferential language detected: {inferences}"})

    # 5. Citation invention check
    case_cit_pat = re.compile(
        r'\b([A-Z][A-Za-z&\s\.]{2,40}?\s+v\.\s+[A-Z][A-Za-z&\s,\.]{2,60}?)\s*,?\s*'
        r'((?:\(\d{4}\)|\[\d{4}\])\s*\d+\s*[A-Z]+\s*\d+|'
        r'\d{4}\s*\(\d+\)\s*[A-Z]+\s*\d+|'
        r'\d{4}\s+SCC\s+OnLine\s+[A-Z]+\s+\d+)'
    )
    invented = []
    output_citations = []
    for m in case_cit_pat.finditer(output):
        case_name = m.group(1).strip()
        citation = m.group(2).strip()
        output_citations.append((case_name, citation))
        # Case name first 15 chars should appear in doc_text
        if case_name[:15].lower() not in doc_text.lower():
            invented.append({"case": case_name, "citation": citation})
    if invented:
        issues.append({"type": "INVENTED_CITATIONS", "severity": "CRITICAL",
                       "note": f"{len(invented)} case citation(s) not present in document",
                       "citations": invented[:5]})

    sev_w = {"CRITICAL": 10, "HIGH": 5, "MEDIUM": 2, "LOW": 1}
    penalty = sum(sev_w.get(i.get("severity"), 0) for i in issues)
    score = max(0.0, 1.0 - penalty / 30.0)
    passed = not any(i.get("severity") in ("CRITICAL", "HIGH") for i in issues)
    logger.info(f"[Agent 6] {'PASS' if passed else 'FAIL'} | issues={len(issues)} | score={score:.2f}")
    return {"passed": passed, "issues": issues, "score": round(score, 2),
            "para_refs_used": refs, "para_refs_invalid": invalid,
            "citations_in_output": len(output_citations),
            "citations_invented": len(invented)}


# ══════════════════════════════════════════════════════════════════════════
# PIPELINE
# ══════════════════════════════════════════════════════════════════════════

async def run_summarizer_pipeline(groq_client, doc_text: str, ocr_quality: str,
                                  output_format: str = "detailed_digest",
                                  modules_requested: List[str] = None,
                                  user_instructions: str = "") -> Dict[str, Any]:
    t0 = time.time()
    pi = {"agents_used": [], "retries": 0}
    modules_requested = modules_requested or []

    anchored_text, anchor_map = anchor_document(doc_text)
    logger.info(f"Doc anchored: {len(anchor_map)} paragraphs")

    # [1/6]
    logger.info("[1/6] Identifying document...")
    identification = await identify_document(groq_client, doc_text, ocr_quality)
    pi["agents_used"].append("identifier")
    pi["identification"] = {"type": identification["document_type"],
                            "framework": identification["framework_code"]}

    # [2/6]
    logger.info("[2/6] Inspecting document quality...")
    quality_report = inspect_document_quality(doc_text, ocr_quality)
    pi["agents_used"].append("quality_inspector")
    pi["quality"] = {"ocr_quality": ocr_quality,
                     "issues_count": len(quality_report["issues"])}

    if any(i["type"] == "EXTRACTION_FAILED" for i in quality_report["issues"]):
        return {"success": False,
                "error": "Document extraction failed \u2014 cannot proceed",
                "quality_report": quality_report,
                "disclaimer": DISCLAIMER_TEXT, "pipeline": pi}

    # [3/6]
    logger.info("[3/6] Extracting framework fields...")
    extraction = await extract_framework_fields(groq_client, anchored_text, identification)
    pi["agents_used"].append("extractor")
    pi["extraction"] = {"framework": extraction["framework_code"],
                        "fields_populated": sum(
                            1 for k, v in extraction["fields"].items()
                            if not k.startswith("_") and v and v != "NOT MENTIONED IN DOCUMENT")}

    # [4/6]
    logger.info("[4/6] Running analytical modules...")
    module_results = await run_modules(groq_client, anchored_text, identification,
                                       extraction, modules_requested)
    pi["agents_used"].append("module_runner")
    pi["modules"] = {"active": module_results["active_modules"],
                     "auto_triggered": module_results["auto_triggered"]}

    # [5/6]
    logger.info(f"[5/6] Formatting output ({output_format})...")
    final_output = await format_output(groq_client, anchored_text, identification,
                                       extraction, module_results, output_format)
    pi["agents_used"].append("formatter")

    # [6/6]
    logger.info("[6/6] Verifying source grounding...")
    verification = verify_source_grounding(final_output, doc_text, anchor_map)
    pi["agents_used"].append("verifier")

    # Retry with feedback if grounding failed
    if not verification["passed"] and MAX_RETRY_LOOPS > 0:
        logger.warning(f"  grounding FAILED \u2014 retrying with verifier feedback")
        pi["retries"] += 1
        feedback_str = json.dumps([{"type": i["type"], "note": i["note"]}
                                    for i in verification["issues"]], indent=2)
        final_output_retry = await format_output(
            groq_client, anchored_text, identification, extraction, module_results,
            output_format, retry_feedback=feedback_str)
        verification_retry = verify_source_grounding(final_output_retry, doc_text, anchor_map)
        pi["agents_used"].extend(["formatter_retry", "verifier_retry"])
        if verification_retry["score"] >= verification["score"]:
            final_output = final_output_retry
            verification = verification_retry

    pi["total_time_ms"] = int((time.time() - t0) * 1000)

    # Build Document Integrity Note
    integrity_lines = []
    if ocr_quality not in ("NotOCR", "High"):
        integrity_lines.append(f"OCR Quality: {ocr_quality} \u2014 verify critical figures/dates against original.")
    for issue in quality_report["issues"]:
        if issue["severity"] in ("HIGH", "CRITICAL"):
            integrity_lines.append(f"{issue['type']}: {issue.get('note', '')}")
    if not integrity_lines:
        integrity_lines.append("Document appears clear and complete. No quality issues detected.")
    integrity_note = "\n".join(integrity_lines)

    logger.info(f"DONE: {identification['document_type']} | format={output_format} | "
                f"grounding_score={verification['score']} | {pi['total_time_ms']}ms")

    return {"success": True,
            "identification": identification,
            "framework_used": extraction["framework_code"],
            "framework_name": extraction["framework_name"],
            "extracted_fields": extraction["fields"],
            "modules": module_results["modules"],
            "modules_active": module_results["active_modules"],
            "output_format": output_format,
            "formatted_output": final_output,
            "quality_report": quality_report,
            "verification": verification,
            "document_integrity_note": integrity_note,
            "disclaimer": DISCLAIMER_TEXT,
            "anchor_count": len(anchor_map),
            "pipeline": pi}


