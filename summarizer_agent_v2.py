# AGENT 2 — OCR/QUALITY INSPECTOR (Step 7)
# ══════════════════════════════════════════════════════════════════════════

def inspect_document_quality(doc_text: str, ocr_quality: str) -> Dict[str, Any]:
    issues = []
    garbled = []

    if ocr_quality == "Failed":
        issues.append({"type": "EXTRACTION_FAILED", "severity": "CRITICAL",
                       "note": "PDF extraction failed entirely \u2014 analysis cannot proceed."})
    elif ocr_quality == "Poor":
        issues.append({"type": "OCR_QUALITY_POOR", "severity": "HIGH",
                       "note": "OCR produced text with low alphanumeric ratio \u2014 many sections may be misread."})
    elif ocr_quality == "Moderate":
        issues.append({"type": "OCR_QUALITY_MODERATE", "severity": "MEDIUM",
                       "note": "OCR usable but verify critical figures/names/dates against original."})

    # Garbled text detection
    for m in re.finditer(r'\b[A-Za-z]*[^\w\s]{3,}[A-Za-z]*\b', doc_text):
        s = m.group(0)
        if 5 < len(s) < 60:
            garbled.append(s)
            if len(garbled) >= 10: break
    if garbled:
        issues.append({"type": "GARBLED_STRINGS", "severity": "MEDIUM",
                       "note": f"Found {len(garbled)} potentially garbled string(s)",
                       "samples": garbled[:5]})

    # Annexure references
    annex_refs = set()
    for m in re.finditer(r'\b[Aa]nnex(?:ure)?\s*[\-\u2013]?\s*([A-Z0-9]+)\b', doc_text):
        annex_refs.add(m.group(1).upper())
    if annex_refs:
        present = set()
        for a in annex_refs:
            if re.search(rf'^\s*[Aa]nnex(?:ure)?\s*[\-\u2013]?\s*{re.escape(a)}\s*[:\-]?\s*$',
                         doc_text, re.MULTILINE):
                present.add(a)
        missing = annex_refs - present
        if missing:
            issues.append({"type": "ANNEXURES_REFERENCED_NOT_ATTACHED",
                           "severity": "MEDIUM",
                           "note": f"Document references {len(missing)} annexure(s) that may not be attached",
                           "annexures": sorted(missing)})

    # Page-break sanity (OCR mode)
    illegible = []
    if "--- PAGE BREAK ---" in doc_text:
        pages = doc_text.split("--- PAGE BREAK ---")
        for i, p in enumerate(pages, 1):
            if len(p.strip()) < 30 and i < len(pages):
                illegible.append(i)
        if illegible:
            issues.append({"type": "PAGES_NEAR_EMPTY", "severity": "HIGH",
                           "note": f"{len(illegible)} page(s) had very little extracted text",
                           "pages": illegible[:10]})

    if len(doc_text) < 500:
        issues.append({"type": "DOCUMENT_TOO_SHORT", "severity": "CRITICAL",
                       "note": f"Document text is only {len(doc_text)} chars \u2014 likely extraction failure."})

    sev_rank = {"CRITICAL": 0, "HIGH": 1, "MEDIUM": 2, "LOW": 3}
    issues.sort(key=lambda i: sev_rank.get(i.get("severity"), 9))
    logger.info(f"[Agent 2] {len(issues)} quality issue(s) | OCR={ocr_quality}")
    return {"ocr_quality": ocr_quality, "issues": issues}


