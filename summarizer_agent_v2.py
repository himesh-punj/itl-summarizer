# AGENT 3 — FRAMEWORK EXTRACTOR (Step 2)
# ══════════════════════════════════════════════════════════════════════════

async def extract_framework_fields(groq_client, doc_text: str,
                                   identification: Dict[str, Any]) -> Dict[str, Any]:
    t0 = time.time()
    fw = identification["framework_code"]
    fields = FRAMEWORKS[fw]["fields"]
    fw_name = FRAMEWORKS[fw]["name"]
    field_specs = "\n".join(f"  - {f}" for f in fields)

    system = f"""You are a legal document field extractor applying Framework {fw} ({fw_name}).

ABSOLUTE RULES (NON-NEGOTIABLE):
1. Extract ONLY what is expressly stated in the document. Never infer, never paraphrase legal conclusions.
2. For each field, cite paragraph references like [\u00b65], [\u00b612], or list multiple as [\u00b65, \u00b612].
3. If a field is not present in the document, return "NOT MENTIONED IN DOCUMENT" \u2014 do not guess.
4. For operative findings, holdings, orders \u2014 reproduce VERBATIM where critical, with [\u00b6N] anchor.
5. Do NOT import external case laws, statutes, or facts that are not in the document.
6. Banned phrases: "typically", "generally", "in practice", "it is well-settled". These signal inferred content.

EXTRACTION FIELDS for Framework {fw}:
{field_specs}

Return JSON ONLY with each field name as a key. Each value should be either:
  (a) A string containing the extracted content + paragraph anchor(s), OR
  (b) An array of strings (for fields with naturally multiple items), OR
  (c) The literal string "NOT MENTIONED IN DOCUMENT"

EXAMPLE (Framework A):
{{
  "court_and_bench": "Hon'ble High Court of Delhi, Coram: J. R.K. Sharma [\u00b61]",
  "case_citation": "W.P.(C) 1234/2024 [\u00b61]",
  "ratio_decidendi": "Where supplier defaults in remitting tax, recipient cannot be denied ITC if conditions of Section 16(2)(a)(b)(d) are met [\u00b645].",
  "precedents_cited_by_court": [
    "Mohit Minerals (P) Ltd. v. UOI, 2022 SCC OnLine SC 657 [\u00b632]"
  ],
  "dissenting_opinion": "NOT MENTIONED IN DOCUMENT"
}}"""

    doc_for_extract = doc_text[:MAX_DOC_CHARS]
    if len(doc_text) > MAX_DOC_CHARS:
        logger.warning(f"  doc truncated: {len(doc_text)} \u2192 {MAX_DOC_CHARS} chars")

    user_prompt = f"""Document Type (per identifier): {identification.get('document_type')}
Framework: {fw} ({fw_name})

DOCUMENT (with paragraph anchors):
{doc_for_extract}

Extract all fields per Framework {fw}. Return JSON only."""

    try:
        resp = groq_client.chat.completions.create(
            model=EXTRACTOR_MODEL,
            messages=[{"role":"system","content":system},
                      {"role":"user","content":user_prompt}],
            temperature=0.1, max_tokens=6000)
        raw = resp.choices[0].message.content.strip()
        if "</think>" in raw: raw = raw.split("</think>")[-1].strip()
        s, e = raw.find("{"), raw.rfind("}")+1
        extracted = json.loads(raw[s:e]) if s>=0 and e>s else {}
    except Exception as ex:
        logger.error(f"Extractor failed: {ex}")
        extracted = {f: "NOT MENTIONED IN DOCUMENT" for f in fields}

    for f in fields:
        if f not in extracted:
            extracted[f] = "NOT MENTIONED IN DOCUMENT"

    # Hybrid: also extract secondary framework
    secondary = identification.get("secondary_framework")
    if identification.get("is_hybrid") and secondary and secondary in FRAMEWORKS and secondary != fw:
        logger.info(f"  hybrid \u2014 also extracting framework {secondary}")
        secondary_extracted = await extract_framework_fields(
            groq_client, doc_text,
            {**identification, "framework_code": secondary, "is_hybrid": False})
        extracted["_secondary_framework"] = {
            "code": secondary,
            "name": FRAMEWORKS[secondary]["name"],
            "fields": {k: v for k, v in secondary_extracted["fields"].items()
                       if not k.startswith("_")}
        }

    elapsed = int((time.time()-t0)*1000)
    populated = sum(1 for k, v in extracted.items()
                    if not k.startswith("_") and v and v != "NOT MENTIONED IN DOCUMENT")
    logger.info(f"[Agent 3] framework={fw} | {populated}/{len(fields)} populated | {elapsed}ms")
    return {"framework_code": fw, "framework_name": fw_name,
            "fields": extracted, "extract_time_ms": elapsed}


