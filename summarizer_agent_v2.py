    ident.setdefault("parties", [])
    ident.setdefault("subject_matter", "NOT MENTIONED IN DOCUMENT")
    ident.setdefault("applicable_law", [])
    ident["framework_code"] = fw
    ident["framework_name"] = FRAMEWORKS[fw]["name"]
    ident["ocr_quality"] = ocr_quality
    ident["identify_time_ms"] = int((time.time()-t0)*1000)
    logger.info(f"[Agent 1] type={ident['document_type']} | framework={fw} | "
                f"OCR={ocr_quality} | {ident['identify_time_ms']}ms")
    return ident


