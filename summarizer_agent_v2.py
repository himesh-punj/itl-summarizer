def extract_text_from_pdf(content) -> Tuple[str, str]:
    """Cascading PDF extraction. Returns (text, ocr_quality)
    where ocr_quality is High/Moderate/Poor/NotOCR/Failed."""
    errors = []
    best = ""

    try:
        import PyPDF2
        reader = PyPDF2.PdfReader(BytesIO(content))
        if reader.is_encrypted:
            try: reader.decrypt("")
            except Exception: pass
        t = "\n".join((p.extract_text() or "") for p in reader.pages).strip()
        if len(t) >= 500: return t, "NotOCR"
        if len(t) > len(best): best = t
        errors.append(f"PyPDF2: short ({len(t)} chars)")
    except Exception as e:
        errors.append(f"PyPDF2: {type(e).__name__}: {e}")

    try:
        import pdfplumber
        with pdfplumber.open(BytesIO(content)) as pdf:
            t = "\n".join((p.extract_text() or "") for p in pdf.pages).strip()
        if len(t) >= 500: return t, "NotOCR"
        if len(t) > len(best): best = t
        errors.append(f"pdfplumber: short ({len(t)} chars)")
    except ImportError: errors.append("pdfplumber not installed")
    except Exception as e: errors.append(f"pdfplumber: {type(e).__name__}: {e}")

    try:
        import fitz
        doc = fitz.open(stream=content, filetype="pdf")
        t = "\n".join(page.get_text() for page in doc).strip()
        doc.close()
        if len(t) >= 500: return t, "NotOCR"
        if len(t) > len(best): best = t
        errors.append(f"fitz: short ({len(t)} chars)")
    except ImportError: errors.append("PyMuPDF not installed")
    except Exception as e: errors.append(f"fitz: {type(e).__name__}: {e}")

    # OCR fallback with quality assessment
    try:
        import fitz
        from PIL import Image
        import pytesseract
        doc = fitz.open(stream=content, filetype="pdf")
        ocr_pages = []
        confidences = []
        for i, page in enumerate(doc):
            if i >= 30: break
            pix = page.get_pixmap(dpi=200)
            img = Image.frombytes("RGB", [pix.width, pix.height], pix.samples)
            try:
                t = pytesseract.image_to_string(img, lang="eng+hin")
            except pytesseract.TesseractError:
                t = pytesseract.image_to_string(img, lang="eng")
            if t.strip():
                ocr_pages.append(t)
                alnum_ratio = sum(1 for c in t if c.isalnum() or c.isspace()) / max(1, len(t))
                confidences.append(alnum_ratio)
        doc.close()
        if ocr_pages:
            full_text = "\n\n--- PAGE BREAK ---\n\n".join(ocr_pages)
            avg_conf = sum(confidences) / max(1, len(confidences))
            if avg_conf >= 0.92: quality = "High"
            elif avg_conf >= 0.80: quality = "Moderate"
            else: quality = "Poor"
            return full_text, quality
        errors.append("OCR: no text on any page")
    except ImportError as ie:
        errors.append(f"OCR unavailable ({ie})")
    except Exception as e:
        errors.append(f"OCR: {type(e).__name__}: {e}")

    if best:
        return best + f"\n\n[Warning: Extraction incomplete. Tried: {'; '.join(errors[:3])}]", "Poor"
    return f"[PDF extraction failed. Tried: {' | '.join(errors[:4])}]", "Failed"


def extract_text_from_docx(content) -> Tuple[str, str]:
    try:
        import docx
        doc = docx.Document(BytesIO(content))
        paras = [p.text for p in doc.paragraphs if p.text.strip()]
        for table in doc.tables:
            for row in table.rows:
                cells = [c.text.strip() for c in row.cells if c.text.strip()]
                if cells: paras.append(" | ".join(cells))
        t = "\n".join(paras).strip()
        if t: return t, "NotOCR"
    except Exception as e:
        try:
            import mammoth
            r = mammoth.extract_raw_text(BytesIO(content))
            t = (r.value or "").strip()
            if t: return t, "NotOCR"
            return f"[DOCX error: python-docx={e}; mammoth: empty]", "Failed"
        except Exception as e2:
            return f"[DOCX error: python-docx={e}; mammoth={e2}]", "Failed"
    return "[DOCX error: empty document]", "Failed"


def extract_text_from_txt(content) -> Tuple[str, str]:
    try: return content.decode("utf-8"), "NotOCR"
    except: return content.decode("latin-1"), "NotOCR"


