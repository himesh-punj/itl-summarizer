class SummarizeTextRequest(BaseModel):
    document_text: str = Field(..., min_length=50, max_length=200000)
    user_instructions: str = Field(default="", max_length=2000)
    output_format: Optional[str] = Field(default=None)


@app.post("/api/summarize/text", tags=["Summarize"])
async def summarize_text(req: SummarizeTextRequest):
    if not groq_client: raise HTTPException(503, "Not ready")
    output_fmt, modules = parse_user_command(req.user_instructions)
    if req.output_format and req.output_format in OUTPUT_FORMATS:
        output_fmt = req.output_format
    return await run_summarizer_pipeline(
        groq_client, req.document_text, "NotOCR",
        output_format=output_fmt, modules_requested=modules,
        user_instructions=req.user_instructions)


@app.post("/api/summarize/file", tags=["Summarize"])
async def summarize_file(file: UploadFile = File(...),
                          user_instructions: str = Form(""),
                          output_format: str = Form("")):
    if not groq_client: raise HTTPException(503, "Not ready")
    ext = os.path.splitext(file.filename or "")[1].lower()
    if ext not in (".pdf", ".docx", ".txt"):
        raise HTTPException(400, f"Unsupported file type: {ext}")
    content = await file.read()
    if not content: raise HTTPException(400, "Empty file")
    if len(content) > 20 * 1024 * 1024:
        raise HTTPException(400, "File too large (max 20MB)")

    extractors = {".pdf": extract_text_from_pdf,
                  ".docx": extract_text_from_docx,
                  ".txt": extract_text_from_txt}
    doc_text, ocr_quality = extractors[ext](content)
    if doc_text.startswith("[PDF extraction failed") or doc_text.startswith("[DOCX error"):
        raise HTTPException(400, doc_text)
    if len(doc_text) < 50:
        raise HTTPException(400, f"Extracted text too short ({len(doc_text)} chars)")

    output_fmt, modules = parse_user_command(user_instructions)
    if output_format and output_format in OUTPUT_FORMATS:
        output_fmt = output_format
    result = await run_summarizer_pipeline(
        groq_client, doc_text, ocr_quality,
        output_format=output_fmt, modules_requested=modules,
        user_instructions=user_instructions)
    result["source_file"] = {"filename": file.filename,
                              "size_bytes": len(content),
                              "ocr_quality": ocr_quality,
                              "extracted_chars": len(doc_text)}
    return result


